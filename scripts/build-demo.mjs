// Builds public/demo/pump-station/index.html from the live field view
// (public/view/georgeville/index.html) so the homepage demo never drifts.
// Run automatically by `npm run build`. Patches (all asserted):
//   - data files load from ../../view/georgeville/
//   - Production marks stay in this browser only: no PIN, no GET/POST /api/progress
//   - "Try it" tip in the header; "Open the real thing" link; crew PIN/name hidden
// The view page itself is never modified; /view/* keeps noindex, the demo is noindex too
// (it is an iframe target, the homepage is what we want indexed).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const SRC = 'public/view/georgeville/index.html', OUT = 'public/demo/pump-station/index.html';
let h = readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n');
function sub(a, b) { if (!h.includes(a)) throw new Error('demo patch target missing: ' + a.slice(0, 70)); h = h.replace(a, b); }
const BASE = '../../view/georgeville/';
sub("fetch('model.usdz'", "fetch('" + BASE + "model.usdz'");
sub("fetch('meta.json')", "fetch('" + BASE + "meta.json')");
sub("fetch('blocks.b64.txt')", "fetch('" + BASE + "blocks.b64.txt')");
sub("fetch('rebar.b64.txt')", "fetch('" + BASE + "rebar.b64.txt')");
sub('href="model.usdz"', 'href="' + BASE + 'model.usdz"');
// local-only marks
const BS = String.fromCharCode(92);
sub("var JOB = (/" + BS + "/view" + BS + "/([^" + BS + "/]+)/.exec(location.pathname) || [])[1] || 'local', API = '/api/progress/' + encodeURIComponent(JOB);",
    "var JOB = 'demo-georgeville', API = null;");
sub('function flush(){\n    if (syncing) return;',
    "function flush(){\n    if (syncing) return;\n    if (queue.length) setSync('Demo: marks stay on this device only. Refresh clears them.'); else setSync('');\n    return;");
sub('function load(){\n    return fetch(API', 'function load(){\n    return Promise.resolve();\n    return fetch(API');
sub('setInterval(function(){ if (prodOn', 'setInterval(function(){ if (false && prodOn');
// never keep demo marks between visits
sub("var srv = jget('tmm-prog-s-' + JOB, []), queue = jget('tmm-prog-q-' + JOB, [])", "var srv = [], queue = []");
sub('<div><label for="whoPin">', '<div hidden><label for="whoPin">');
sub('<span class="rev" id="rev" hidden></span>',
    '<span class="demo-tip"><b>Try it:</b> tap a wall, pick a lift, tap a bar, turn on <b>Production</b>. <a href="/view/georgeville/" target="_top">Open the real field view</a></span>\n    <span class="rev" id="rev" hidden></span>');
sub('</style>', '.demo-tip{font-size:13px;line-height:1.35;color:var(--ink);opacity:.85;text-align:right;max-width:46ch}.demo-tip a{color:inherit;white-space:nowrap}@media (max-width:520px){.demo-tip{font-size:12px;max-width:60%}.demo-tip a{display:none}}\n</style>');
sub('<title>TMM Field View</title>', '<title>Try a real job - The Masonry Modeler</title>');
h = h.replace('<head>', '<head>\n<!-- GENERATED by scripts/build-demo.mjs from public/view/georgeville/index.html. Do not edit. -->');
mkdirSync('public/demo/pump-station', { recursive: true });
writeFileSync(OUT, h);
console.log('demo built:', OUT, h.length, 'bytes');
